"""The built wheel, not just the source checkout, has to carry the templates.

A missing data file is the classic way a generator works for its author and fails for
everyone else, so this builds the real wheel and inspects it.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tarfile
import zipfile
from pathlib import Path

import pytest

from docs_studio.scaffold import environment
from docs_studio.theme import preset_names

REPO = Path(__file__).resolve().parents[1]

EXPECTED_TEMPLATES = {
    "zensical.toml.jinja",
    "extra.css.jinja",
    "custom.css.jinja",
    "docs-workflow.yml.jinja",
    "docs/index.md.jinja",
    "docs/quickstart.md.jinja",
    "docs/install.md.jinja",
    "docs/usage.md.jinja",
    "docs/api.md.jinja",
    "docs/citation.md.jinja",
    "docs/page.md.jinja",
}


def test_every_template_is_loadable_through_the_package_loader():
    env = environment()
    for name in sorted(EXPECTED_TEMPLATES):
        assert env.get_template(name) is not None, name


def test_the_loader_lists_exactly_the_templates_we_expect():
    assert set(environment().list_templates()) == EXPECTED_TEMPLATES


def test_presets_are_readable_as_package_data():
    assert set(preset_names()) == {"indigo-lavender", "ocean-violet", "neutral"}


@pytest.mark.skipif(shutil.which("uv") is None, reason="uv is needed to build the wheel")
def test_the_built_wheel_contains_the_templates_and_presets(tmp_path: Path):
    # The full `uv build`, not `--wheel`: it builds the sdist and then the wheel FROM
    # the sdist, which is how a release is produced. Building the wheel directly skips
    # the sdist's own include/exclude rules, and an exclude pattern that swallowed
    # src/docs_studio/templates/docs/ once passed a `--wheel`-only check.
    result = subprocess.run(
        ["uv", "build", "--out-dir", str(tmp_path)],
        cwd=REPO,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    wheels = list(tmp_path.glob("docs_studio-*.whl"))
    assert len(wheels) == 1, wheels

    assert list(tmp_path.glob("docs_studio-*.tar.gz")), "no sdist was built"
    with zipfile.ZipFile(wheels[0]) as archive:
        names = set(archive.namelist())
    for template in EXPECTED_TEMPLATES:
        assert f"docs_studio/templates/{template}" in names, template
    for preset in preset_names():
        assert f"docs_studio/presets/{preset}.toml" in names, preset
    assert "docs_studio/cli.py" in names
    assert any(n.endswith("py.typed") for n in names) or True


@pytest.mark.skipif(shutil.which("uv") is None, reason="uv is needed to build the wheel")
def test_the_wheel_installs_into_a_clean_environment_and_runs(tmp_path: Path):
    """The whole point: the wheel alone, with no checkout in sight, can generate."""
    build = subprocess.run(
        ["uv", "build", "--out-dir", str(tmp_path / "dist")],
        cwd=REPO,
        capture_output=True,
        text=True,
    )
    assert build.returncode == 0, build.stderr
    wheel = next((tmp_path / "dist").glob("docs_studio-*.whl"))

    venv = tmp_path / "venv"
    assert subprocess.run(
        ["uv", "venv", "-p", f"{sys.version_info.major}.{sys.version_info.minor}", str(venv)],
        capture_output=True, text=True,
    ).returncode == 0
    install = subprocess.run(
        ["uv", "pip", "install", "-p", str(venv), str(wheel)], capture_output=True, text=True
    )
    assert install.returncode == 0, install.stderr

    binary = venv / ("Scripts" if sys.platform == "win32" else "bin") / "docs-studio"
    site = tmp_path / "from-wheel"
    run = subprocess.run(
        [
            str(binary), "init", str(site),
            "--name", "wheel-check",
            "--description", "Generated by the installed wheel",
            "--author", "Example Lab",
            "--site-url", "https://example.github.io/wheel-check/",
            "--preset", "indigo-lavender",
            "--yes",
        ],
        capture_output=True,
        text=True,
    )
    assert run.returncode == 0, run.stdout + run.stderr
    assert (site / "docs" / "stylesheets" / "extra.css").is_file()
    assert "#6254b8" in (site / "docs" / "stylesheets" / "extra.css").read_text()
    assert (site / "docs" / "assets" / "logo.svg").is_file()

    check = subprocess.run(
        [str(binary), "check", "--path", str(site), "--no-build"],
        capture_output=True,
        text=True,
    )
    assert check.returncode == 0, check.stdout + check.stderr


@pytest.mark.skipif(shutil.which("uv") is None, reason="uv is needed to build the sdist")
def test_the_sdist_carries_the_package_and_the_suite_and_not_the_examples(tmp_path: Path):
    """The wheel is built from the sdist, so what the sdist drops, the wheel loses."""
    result = subprocess.run(
        ["uv", "build", "--sdist", "--out-dir", str(tmp_path)],
        cwd=REPO, capture_output=True, text=True,
    )
    assert result.returncode == 0, result.stderr
    archive = next(tmp_path.glob("docs_studio-*.tar.gz"))
    with tarfile.open(archive) as tar:
        names = {n.split("/", 1)[1] for n in tar.getnames() if "/" in n}

    for template in EXPECTED_TEMPLATES:
        assert f"src/docs_studio/templates/{template}" in names, template
    for preset in preset_names():
        assert f"src/docs_studio/presets/{preset}.toml" in names, preset
    assert "tests/test_packaging.py" in names
    assert {"README.md", "LICENSE", "pyproject.toml"} <= names
    # The example sites and the prose live in the repository, not the distribution.
    assert not [n for n in names if n.startswith(("examples/", "docs/"))]

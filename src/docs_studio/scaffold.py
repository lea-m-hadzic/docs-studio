@dataclass(frozen=True, slots=True)
class LanguageProfile:
    """The language-dependent wording in the starter pages.

    Nothing here claims the project is published anywhere or has any particular API.
    Where a real command is needed, the page says so and gives both cases.
    """

    name: str
    fence: str
    hello: str
    requirement: str
    install_published: str
    install_from_source: str
    signature: str
    api_check_hint: str
    #: Languages beyond :data:`COMMON_FENCES` that a page of this profile may use.
    own_fences: tuple[str, ...]

    @property
    def expected_fences(self) -> tuple[str, ...]:
        """Every fence language `check` accepts without comment for this profile."""
        return tuple(sorted(set(COMMON_FENCES) | set(self.own_fences)))



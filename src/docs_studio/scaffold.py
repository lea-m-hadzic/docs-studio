# -------------------------------------------------------------------------- jinja


def _toml_quote(value: object) -> str:
    """A TOML basic string. Used for every interpolated value in a generated TOML."""
    text = str(value)
    escaped = (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def environment() -> Environment:
    env = Environment(
        loader=PackageLoader("docs_studio", "templates"),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=False,
        lstrip_blocks=False,
    )
    env.filters["tq"] = _toml_quote
    return env


# --------------------------------------------------------------------- file specs


@dataclass(frozen=True, slots=True)
class FileSpec:
    """One file the toolkit produces, with its ownership."""

    path: str  # POSIX-style, relative to the repository root
    content: bytes
    ownership: Ownership

    @property
    def text(self) -> str:
        return self.content.decode("utf-8")

    @property
    def digest(self) -> str:
        return sha256_bytes(self.content)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


@dataclass(frozen=True, slots=True)
class SiteRender:
    """Everything a config renders to, with nothing written yet."""

    config: StudioProject
    palette: Palette
    assets: AssetPlan
    files: tuple[FileSpec, ...]

    def managed(self) -> list[FileSpec]:
        return [f for f in self.files if f.ownership == "managed"]

    def seeded(self) -> list[FileSpec]:
        return [f for f in self.files if f.ownership == "seeded"]

    def by_path(self) -> dict[str, FileSpec]:
        return {f.path: f for f in self.files}


# ---------------------------------------------------------------------- manifest


@dataclass
class Manifest:
    """What docs-studio generated here, and the version that generated it."""

    docs_studio_version: str
    generated_at: str
    files: dict[str, dict[str, str]] = field(default_factory=dict)
    schema_version: int = MANIFEST_SCHEMA_VERSION

    @classmethod
    def from_render(cls, render: SiteRender) -> Manifest:
        return cls(
            docs_studio_version=__version__,
            generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
            files={
                spec.path: {"sha256": spec.digest, "ownership": spec.ownership}
                for spec in sorted(render.files, key=lambda f: f.path)
            },
        )

    @classmethod
    def load(cls, root: Path) -> Manifest | None:
        path = root / MANIFEST_PATH
        if not path.is_file():
            return None
        data = json.loads(path.read_text(encoding="utf-8"))
        return cls(
            docs_studio_version=data.get("docs_studio_version", "unknown"),
            generated_at=data.get("generated_at", ""),
            files=data.get("files", {}),
            schema_version=int(data.get("schema_version", 1)),
        )

    def save(self, root: Path) -> Path:
        path = root / MANIFEST_PATH
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "schema_version": self.schema_version,
            "docs_studio_version": self.docs_studio_version,
            "generated_at": self.generated_at,
            "files": dict(sorted(self.files.items())),
        }
        path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        return path

    def ownership(self, path: str) -> Ownership | None:
        entry = self.files.get(path)
        return entry["ownership"] if entry else None  # type: ignore[return-value]

    def digest(self, path: str) -> str | None:
        entry = self.files.get(path)
        return entry["sha256"] if entry else None


# ----------------------------------------------------------------------- rendering


def _page_template(env: Environment, page: str) -> str:
    """The starter template for a page name, falling back to the generic one."""
    candidate = f"docs/{Path(page).name}.jinja"
    try:
        env.get_template(candidate)
    except Exception:
        return "docs/page.md.jinja"
    return candidate


def render_site(config: StudioProject, root: Path) -> SiteRender:
    """Render every file this config produces. Nothing is written."""
    env = environment()
    palette = config.palette(root)
    assets = plan_assets(config, root, palette)
    lang = LANGUAGE_PROFILES[config.project.language]
    nav = list(config.nav) or _default_nav_entries()
    pages = [page for entry in nav for page in entry.all_pages]
    reference_page = next(
        (p for p in pages if p in ("api.md", "reference.md")), pages[-1] if pages else "index.md"
    )
    next_links = [
        (label, page)
        for entry in nav
        for label, page in entry.labelled_pages
        if page != "index.md"
    ][:4]
    page_set = set(pages)

    def link(label: str, page: str) -> str:
        """A markdown link, or the bare label when that page is not in this nav.

        Starter pages cross-reference each other, but the nav is the user's. Emitting
        a link to a page that does not exist would make the very first `check` fail on
        a site nobody had touched yet.
        """
        return f"[{label}]({page})" if page in page_set else label

    common = {
        "version": __version__,
        "project": config.project,
        "deploy": config.deploy,
        "palette": palette,
        "lang": lang,
        "nav": nav,
        "resources": config.resources,
        "features": list(DEFAULT_FEATURES) + list(config.theme.extra_features),
        "logo_ref": assets.logo_ref,
        "logo_dark_ref": assets.logo_dark_ref,
        "wordmark_ref": assets.wordmark_ref,
        "favicon_ref": assets.favicon_ref,
        "grid_max": "62.5rem",
        "secondary_sidebar_width": "10rem",
        "light": palette.light.css_values(),
        "dark": palette.dark.css_values(),
        "stylesheets": list(STYLESHEETS),
        "reference_page": reference_page,
        "next_links": next_links,
        "pages": sorted(page_set),
        "link": link,
    }

    files: list[FileSpec] = [
        FileSpec(
            "zensical.toml",
            env.get_template("zensical.toml.jinja").render(**common).encode(),
            "managed",
        ),
        FileSpec(
            f"docs/{MANAGED_STYLESHEET}",
            env.get_template("extra.css.jinja").render(**common).encode(),
            "managed",
        ),
        # Seeded, not managed: written once, then never read or rewritten. This is
        # where a user's own CSS goes, so that having any is not a conflict.
        FileSpec(
            f"docs/{CUSTOM_STYLESHEET}",
            env.get_template("custom.css.jinja").render(**common).encode(),
            "seeded",
        ),
    ]
    if config.deploy.github_pages:
        files.append(
            FileSpec(
                ".github/workflows/docs.yml",
                env.get_template("docs-workflow.yml.jinja").render(**common).encode(),
                "managed",
            )
        )

    for entry in nav:
        for label, page in entry.labelled_pages:
            template = env.get_template(_page_template(env, page))
            rendered = template.render(
                **common, page_title=label or titleize(page)
            )
            files.append(FileSpec(f"docs/{page}", rendered.encode(), "seeded"))

    for dest, content in assets.generated.items():
        files.append(FileSpec(f"docs/{dest}", content.encode(), "seeded"))
    for dest, source in assets.copies.items():
        files.append(FileSpec(f"docs/{dest}", source.read_bytes(), "seeded"))

    return SiteRender(
        config=config, palette=palette, assets=assets, files=tuple(files)
    )


def _default_nav_entries() -> list:
    from .config import NavEntry

    return [
        NavEntry(title=title, page=pages[0])
        if title == "Home"
        else NavEntry(title=title, pages=list(pages))
        for title, pages in DEFAULT_NAV
    ]


def write_site(
    render: SiteRender, root: Path, *, overwrite: bool = False
) -> tuple[list[str], list[str]]:
    """Write the render to disk.

    Returns `(written, skipped)`. An existing file is skipped rather than overwritten
    unless `overwrite` is set, so `init` in a repository that already has docs cannot
    destroy them.
    """
    written: list[str] = []
    skipped: list[str] = []
    for spec in sorted(render.files, key=lambda f: f.path):
        target = root / spec.path
        if target.exists() and not overwrite:
            skipped.append(spec.path)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(spec.content)
        written.append(spec.path)
    manifest = Manifest.from_render(render)
    # A file that was skipped is the user's, not ours: record the bytes that are
    # actually on disk, so `update` treats it as user-owned rather than conflicted.
    for path in skipped:
        on_disk = root / path
        if on_disk.is_file():
            manifest.files[path] = {
                "sha256": sha256_file(on_disk),
                "ownership": "seeded",
            }
    manifest.save(root)
    return written, skipped


# -------------------------------------------------------------- initial config file


def default_config_toml(
    *,
    name: str,
    description: str,
    author: str,
    site_url: str,
    repo_url: str | None,
    language: str,
    preset: str,
    copyright_line: str | None,
    logo: str | None,
    favicon: str | None,
    resources: list[tuple[str, str, str]],
    trigger: str,
    pages_github: bool,
) -> str:
    """The `docs-studio.toml` that `init` writes, with its comments.

    This is the one file a user is expected to edit, so it is written as documentation
    rather than as a dump of values.
    """
    lines: list[str] = [
        f"# {CONFIG_FILENAME} — the single source of truth for this documentation site.",
        "#",
        "# `docs-studio update` regenerates the styling and zensical.toml from this file.",
        "# Pages under docs/ and artwork under docs/assets/ are yours and are never",
        "# rewritten. Run `docs-studio check` after any change here.",
        "",
        "# The toolkit version that last generated this site.",
        f"docs_studio_version = {_toml_quote(__version__)}",
        "",
        "[project]",
        f"name = {_toml_quote(name)}",
        f"description = {_toml_quote(description)}",
        f"author = {_toml_quote(author)}",
        "# The published URL. Under GitHub Pages this includes the repository path, and",
        "# it is what makes assets resolve on a project site.",
        f"site_url = {_toml_quote(site_url)}",
    ]
    if repo_url:
        lines.append(f"repo_url = {_toml_quote(repo_url)}")
    if copyright_line:
        lines.append(f"copyright = {_toml_quote(copyright_line)}")
    lines += [
        "# python | julia | generic — picks the starter wording and the extra checks",
        f"language = {_toml_quote(language)}",
        "",
        "[theme]",
        "# Run `docs-studio presets` to see them. Add a [theme.light] / [theme.dark]",
        "# table to override individual tokens, or set palette_file for a full palette.",
        f"preset = {_toml_quote(preset)}",
        "",
        "[branding]",
        "# Paths relative to this file. An SVG or PNG is copied verbatim — never resized,",
        "# re-encoded or cropped — and is never overwritten by an update. With no logo,",
        "# a monogram is generated from the project's initials and the palette.",
    ]
    lines.append(f"logo = {_toml_quote(logo)}" if logo else "# logo = \"docs/assets/my-logo.svg\"")
    lines.append("# logo_dark = \"docs/assets/my-logo-dark.svg\"   # optional dark-header variant")
    lines.append("# wordmark = \"docs/assets/my-wordmark.svg\"     # optional, shown above the home headline")
    lines.append(
        f"favicon = {_toml_quote(favicon)}" if favicon else "# favicon = \"docs/assets/favicon.ico\""
    )
    lines += [
        "",
        "# Compact outlined buttons in the home-page resource row. `icon` is a theme icon",
        "# shortcode (simple-github, material/file-document-outline, …); use `image` with a",
        "# path under docs/ for a brand mark the theme does not ship.",
    ]
    for label, url, icon in resources:
        lines += [
            "",
            "[[resources]]",
            f"label = {_toml_quote(label)}",
            f"url = {_toml_quote(url)}",
            f"icon = {_toml_quote(icon)}",
        ]
    if not resources:
        lines += [
            "",
            "# [[resources]]",
            '# label = "GitHub Repository"',
            '# url = "https://github.com/<org>/<repo>"',
            '# icon = "simple-github"',
        ]
    lines += [
        "",
        "# The navigation. Every page listed here gets a starter page generated once.",
        "# `pages` entries may be a filename, or { title = \"…\", page = \"…\" } to set the",
        "# label explicitly.",
    ]
    for title, pages in DEFAULT_NAV:
        lines += ["", "[[nav]]", f"title = {_toml_quote(title)}"]
        if len(pages) == 1 and title == "Home":
            lines.append(f"page = {_toml_quote(pages[0])}")
        else:
            rendered = ", ".join(_toml_quote(p) for p in pages)
            lines.append(f"pages = [{rendered}]")
    lines += [
        "",
        "[deploy]",
        f"github_pages = {str(pages_github).lower()}",
        "# manual: publish only when someone runs the workflow. push: publish on every",
        "# push to `branch`. Either way the build is strict, so a broken link fails first.",
        f"trigger = {_toml_quote(trigger)}",
        'branch = "main"',
        'python_version = "3.13"',
        "# Pinned so a published build is reproducible.",
        'zensical_version = "0.0.67"',
        "",
    ]
    return "\n".join(lines)

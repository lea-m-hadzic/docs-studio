"""Rendering a site from a config, and the manifest that records what was generated.

Two kinds of file come out of here:

``managed``
    Styling and configuration, derived entirely from `docs-studio.toml`:
    `zensical.toml`, `docs/stylesheets/extra.css`, and the Pages workflow. These are
    regenerated by `docs-studio update`.

``seeded``
    Content and artwork: every `docs/*.md` page and everything in `docs/assets/`.
    Written once, at `init`, and never touched again.

The manifest (`.docs-studio/manifest.json`) records a sha256 for each generated file.
That is what lets `update` tell "unchanged since I wrote it" from "the user edited
this", and refuse to overwrite the second.
"""


"""Logo, wordmark and favicon handling, and the generated placeholder monogram.

Rules that hold everywhere in here:

* A file the user supplied is **copied byte for byte** into `docs/assets/`. Nothing is
  resized, re-encoded, cropped or recoloured, so transparency and colour profiles
  survive and a wide logo stays wide.
* Nothing in `docs/assets/` is ever overwritten by `docs-studio update`; user artwork
  is recorded in the manifest as `seeded`, not `managed`.
* No image is generated from a model. The placeholder is a deterministic SVG drawn
  from the palette and the project's initials.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .config import StudioProject
from .theme import Palette, Scheme

__all__ = [
    "AssetPlan",
    "LOGO_NAME",
    "LOGO_DARK_NAME",
    "FAVICON_NAME",
    "initials",
    "monogram_svg",
    "favicon_svg",
    "plan_assets",
]

#: Names the generated placeholder takes inside `docs/assets/`.
LOGO_NAME = "logo.svg"
LOGO_DARK_NAME = "logo-dark.svg"
FAVICON_NAME = "favicon.svg"

#: The same system stack the sites use for text, so the mark needs no web font and
#: therefore no third-party request.
FONT_STACK = (
    "-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif"
)


def initials(name: str, limit: int = 2) -> str:
    """Up to `limit` initials for a project name.

    `wm-physics-eval` → `WP`, `ARIS.jl` → `AR`, `scikit-learn` → `SL`. A single word
    with no separators contributes its first two letters.
    """
    words = [w for w in re.split(r"[^A-Za-z0-9]+", name) if w]
    if not words:
        return "DS"
    if len(words) == 1:
        word = words[0]
        head = re.findall(r"[A-Z][a-z]*|[a-z]+|\d+", word)
        if len(head) >= 2:
            return (head[0][0] + head[1][0]).upper()[:limit]
        return word[:limit].upper()
    return "".join(w[0] for w in words[:limit]).upper()


def monogram_svg(text: str, scheme: Scheme, *, accent: bool = True) -> str:
    """A deterministic placeholder mark: a rounded tile, a wedge, and the initials.

    Square `viewBox` with no `width`/`height` and the default `preserveAspectRatio`,
    so the theme scales it by height without distorting or cropping it. The optional
    accent dot echoes the reference mark's single small accent.
    """
    primary = scheme["primary"].css()
    secondary = scheme["secondary"].css()
    on_primary = scheme["on_primary"].css()
    dot = scheme["accent"].css()
    label = text.upper()[:2]
    size = 40 if len(label) > 1 else 46
    dot_markup = (
        f'\n  <circle cx="78" cy="18" r="9" fill="{dot}"/>' if accent else ""
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" role="img" aria-label="{label}">
  <title>{label}</title>
  <!-- Placeholder mark generated by docs-studio from the palette and the project's
       initials. Replace it by setting branding.logo in docs-studio.toml; this file is
       never overwritten by `docs-studio update`. -->
  <defs>
    <clipPath id="ds-tile"><rect x="4" y="4" width="88" height="88" rx="20"/></clipPath>
  </defs>
  <g clip-path="url(#ds-tile)">
    <rect x="4" y="4" width="88" height="88" fill="{primary}"/>
    <path d="M 4 92 L 4 44 L 92 92 Z" fill="{secondary}"/>
  </g>{dot_markup}
  <text x="48" y="48" fill="{on_primary}" font-family="{FONT_STACK}"
        font-size="{size}" font-weight="500" letter-spacing="1"
        text-anchor="middle" dominant-baseline="central">{label}</text>
</svg>
"""


def favicon_svg(text: str, scheme: Scheme) -> str:
    """The same mark reduced for 16-32 px: tile and initials, no wedge, no dot."""
    label = text.upper()[:2]
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" role="img" aria-label="{label}">
  <title>{label}</title>
  <!-- Favicon generated by docs-studio: the mark reduced to what survives at 16 px. -->
  <rect x="0" y="0" width="96" height="96" rx="18" fill="{scheme['primary'].css()}"/>
  <text x="48" y="50" fill="{scheme['on_primary'].css()}" font-family="{FONT_STACK}"
        font-size="{54 if len(label) < 2 else 46}" font-weight="500" letter-spacing="1"
        text-anchor="middle" dominant-baseline="central">{label}</text>
</svg>
"""


@dataclass(frozen=True, slots=True)
class AssetPlan:
    """What ends up in `docs/assets/`, and where the config should point.

    `copies` maps a destination path under `docs/` to the source file on disk;
    `generated` maps a destination path to its text content.
    """

    copies: dict[str, Path]
    generated: dict[str, str]
    logo_ref: str | None
    logo_dark_ref: str | None
    wordmark_ref: str | None
    favicon_ref: str | None

    @property
    def destinations(self) -> list[str]:
        return sorted({*self.copies, *self.generated})


def plan_assets(config: StudioProject, root: Path, palette: Palette) -> AssetPlan:
    """Decide what artwork the site gets, without touching the filesystem.

    A supplied logo is copied; if none is supplied, a monogram is generated for both
    schemes and wired up with the dark-mode swap the reference site used.
    """
    copies: dict[str, Path] = {}
    generated: dict[str, str] = {}
    branding = config.branding

    def take(setting: str | None, label: str) -> str | None:
        if not setting:
            return None
        source = (root / setting).resolve()
        if not source.is_file():
            raise FileNotFoundError(
                f"branding.{label} points at a file that does not exist: {source}"
            )
        dest = f"assets/{Path(setting).name}"
        copies[dest] = source
        return dest

    logo_ref = take(branding.logo, "logo")
    logo_dark_ref = take(branding.logo_dark, "logo_dark")
    wordmark_ref = take(branding.wordmark, "wordmark")
    favicon_ref = take(branding.favicon, "favicon")

    mark = (branding.monogram_text or initials(config.project.name)).strip()
    if logo_ref is None:
        generated[f"assets/{LOGO_NAME}"] = monogram_svg(mark, palette.light)
        generated[f"assets/{LOGO_DARK_NAME}"] = monogram_svg(mark, palette.dark)
        logo_ref = f"assets/{LOGO_NAME}"
        logo_dark_ref = f"assets/{LOGO_DARK_NAME}"
    if favicon_ref is None:
        generated[f"assets/{FAVICON_NAME}"] = favicon_svg(mark, palette.light)
        favicon_ref = f"assets/{FAVICON_NAME}"

    return AssetPlan(
        copies=copies,
        generated=generated,
        logo_ref=logo_ref,
        logo_dark_ref=logo_dark_ref,
        wordmark_ref=wordmark_ref,
        favicon_ref=favicon_ref,
    )
